"""Encrypt content.html into payload.js so it can be published without exposing the content.

Usage:
    .venv/bin/python encrypt.py            # prompts for the password
    SITE_PASSWORD=secret .venv/bin/python encrypt.py
"""

import base64
import getpass
import hashlib
import json
import os
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = Path(__file__).parent
ITERATIONS = 250_000


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def main() -> None:
    password = os.environ.get("SITE_PASSWORD") or getpass.getpass("Site password: ")
    if not password:
        raise SystemExit("Password must not be empty.")

    plaintext = (ROOT / "content.html").read_bytes()
    salt = os.urandom(16)
    iv = os.urandom(12)
    key = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS, dklen=32)
    ciphertext = AESGCM(key).encrypt(iv, plaintext, None)

    payload = {
        "iterations": ITERATIONS,
        "salt": b64(salt),
        "iv": b64(iv),
        "ciphertext": b64(ciphertext),
    }
    (ROOT / "payload.js").write_text(
        "// Generated by encrypt.py. Do not edit by hand.\n"
        f"const PAYLOAD = {json.dumps(payload, indent=2)};\n"
    )
    print("Wrote payload.js")


if __name__ == "__main__":
    main()
